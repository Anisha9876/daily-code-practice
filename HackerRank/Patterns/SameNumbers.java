package HackerRank.Patterns;

public class SameNumbers {
    public static void main(String[] args) {
//        1 1 1
//        2 2 2
//        3 3 3
        for(int i=0;i<3;i++){
            for(int j=0;j<3;j++){
                System.out.print((i+1)+" ");
            }
            System.out.println();
        }
    }
}
